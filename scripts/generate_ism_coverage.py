"""Generate and verify docs/ism-coverage.md from mappings/ism.csv.

Usage:
    python scripts/generate_ism_coverage.py          # write docs/ism-coverage.md
    python scripts/generate_ism_coverage.py --check  # exit 1 if out of date
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
ISM_CSV = REPO_ROOT / "mappings" / "ism.csv"
OUT_MD = REPO_ROOT / "docs" / "ism-coverage.md"


def render_markdown(rows: list[dict[str, str]]) -> str:
    releases = sorted({r["ism_release"] for r in rows if r.get("ism_release")})
    release_str = ", ".join(releases) if releases else "Unspecified"

    unique_controls = sorted({r["ism_control_id"] for r in rows})
    by_strategy = Counter(r["strategy"] for r in rows)
    by_type = Counter(r["artefact_type"] for r in rows)

    lines: list[str] = [
        "# ISM control coverage matrix",
        "",
        "<!-- Generated by scripts/generate_ism_coverage.py from mappings/ism.csv. Do not edit by hand. -->",
        "",
        f"This table maps every analytics rule, hunting query and workbook tile in `Solution/` to control identifiers from the [ASD Information Security Manual (ISM)](https://www.cyber.gov.au/resources-business-and-government/essential-cyber-security/ism) (**{release_str}**).",
        "",
        "## Summary",
        "",
        f"- **ISM release:** {release_str}",
        f"- **Distinct ISM controls mapped:** {len(unique_controls)}",
        f"- **Total mappings:** {len(rows)}",
        f"- **Analytics rules mapped:** {by_type.get('analytic_rule', 0)}",
        f"- **Hunting queries mapped:** {by_type.get('hunting_query', 0)}",
        f"- **Workbook tiles mapped:** {by_type.get('workbook_tile', 0)}",
        "",
        "### Coverage by Essential Eight strategy",
        "",
        "| Strategy | Mapped artefacts and tiles |",
        "| :--- | :--- |",
    ]
    for strat, count in sorted(by_strategy.items()):
        lines.append(f"| `{strat}` | {count} |")

    lines.extend(
        [
            "",
            "## Full mapping table",
            "",
            "| ISM Control | Strategy | Requirement | ML | Type | Artefact | Tile / Rule |",
            "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
        ]
    )

    for row in rows:
        artefact_link = f"`{row['artefact_path']}`"
        lines.append(
            f"| `{row['ism_control_id']}` | `{row['strategy']}` | `{row['e8_requirement_id']}` | "
            f"ML{row['maturity_level']} | `{row['artefact_type']}` | {artefact_link} | {row['tile_or_rule_name']} |"
        )

    lines.extend(
        [
            "",
            "## Official references",
            "",
            "- [ASD Information Security Manual (ISM)](https://www.cyber.gov.au/resources-business-and-government/essential-cyber-security/ism)",
            "- [ASD Essential Eight Maturity Model](https://www.cyber.gov.au/resources-business-and-government/essential-cyber-security/essential-eight/essential-eight-maturity-model)",
            "",
            "## Disclaimer",
            "",
            "This is an independent community project. It is not produced, endorsed or supported by the Australian Signals Directorate (ASD), the Australian Cyber Security Centre (ACSC) or Microsoft.",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate or verify docs/ism-coverage.md")
    parser.add_argument("--check", action="store_true", help="Fail if docs/ism-coverage.md is out of date")
    args = parser.parse_args(argv)

    with ISM_CSV.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))

    expected = render_markdown(rows)
    if args.check:
        if not OUT_MD.exists() or OUT_MD.read_text(encoding="utf-8") != expected:
            print(
                "docs/ism-coverage.md is out of date. Run: python scripts/generate_ism_coverage.py",
                file=sys.stderr,
            )
            return 1
        print("docs/ism-coverage.md is up to date.")
        return 0

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(expected, encoding="utf-8")
    print(f"Wrote {OUT_MD.relative_to(REPO_ROOT)} ({len(rows)} rows).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
